CORRECTING A FALSE CLAIM

story_arc_prelude.lua's header used to say, verbatim:

    "Chivos's conversation tree is not reconstructed. story_arc_prelude_chivos.stf's
    do_not_edit row says the file "is automatically generated by the
    SwgConversationEditor", so a real branching tree existed, but wiring one needs a
    new mobile/conversations/mustafar/ file, a handler, an include in
    mobile/conversations.lua and a conversationTemplate on the creature -- two of them
    shared files this file is not the owner of. His lines are quoted into the radial
    and its message boxes so that nothing he says is lost in the meantime."

Two things in that were wrong.

ROOT CAUSE 1 -- the search that concluded "a real branching tree existed" but could
not be recovered was scoped to the som_ name prefix, because every quest in this arc
is som_story_arc_prelude_NN. The conversation is not named som_ anything: it is
story_arc_prelude_chivos, and it ships in the BASE string/en/conversation/ set, not
in a som_ table. It was there the whole time.

ROOT CAUSE 2 -- "a conversationTemplate on the creature" was treated as forbidden
work because the brief forbids REPOINTING an existing conversationTemplate.
must_foreman_chivos.lua's field was the empty string. Filling an empty field with a
new template is not repointing anything, and was never forbidden.

THE FIFTEEN-YEAR-OLD RADIAL

Everything Chivos said was already quoted -- into a radial menu and a stack of SUI
message boxes. That stand-in is retired with this file; see the headstone in
story_arc_prelude.lua. Two of its radial labels ("Report the air filters replaced",
"Ask Foreman Chivos about the job") were invented because nothing shipped them.
Both are gone: the real tree has a shipped player line for every step.

ONE BARK, NOT A CONVERSATION

s_27 is delivered on live with chat.chat and an immediate return -- a spatial speech
bubble over his head, no window and no options. Core3 cannot render that from a
conversation, so it becomes a one-line terminal screen here (all_missions_done). The
other seven greetings all call npcStartConversation and open a real window.

TWO SHARED SCREENS

s_36 is reached from two different options and s_124 from two others. s_124 carries
no gesture on either edge, so one plain screen serves both. s_36 does: the npc plays
"sweat" on both edges, which lives on the screen, but the player plays "nod" only on
the edge out of s_34. A playerAnimation field can hold one value, not one per
inbound edge, so that single gesture goes in chivos_conv_handler.edgeAnimations --
the mechanism serpent_thief_conv_handler.lua:98 and obi_wan_conv_handler.lua:157
already use for exactly this case.

ANIMATIONS

ConvoScreen carries native animation (npc) and playerAnimation (player) fields --
ConversationScreen.h:203-208 -- and both belong on the TARGET screen of the edge.
Every gesture live plays is on a screen field here except the one noted above.
--]]

