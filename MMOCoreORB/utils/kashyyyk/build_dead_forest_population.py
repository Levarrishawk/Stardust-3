"""Generate the Dead Forest spawn tables from DSRC. Pass DSRC_ROOT [--check]."""
import argparse
import csv
import math
import re
from pathlib import Path

from build_rryatt_population import SCRIPTS, lua, table, variables


def position(row, area):
    return [round(float(row['px']) + float(area['x1']), 7), float(row['py']),
            round(float(row['pz']) + float(area['z1']), 7)]


def generate(root):
    server = root / 'sku.0/sys.server/compiled/game'
    shared = root / 'sku.0/sys.shared/compiled/game'
    dt = server / 'datatables'
    name = 'kashyyyk_dead_forest'
    area, = table(shared / f'datatables/buildout/areas_{name}.tab')
    rows = table(dt / f'buildout/{name}/{name}.tab')
    creatures = {r['creatureName']: r for r in table(dt / 'mob/creatures.tab')}
    types, controllers, patrols, npcs, cave, points = {}, [], [], [], [], {}
    for line, r in enumerate(rows, 3):
        script = r['scripts']
        v = variables(r['objvars'])
        if script == 'systems.spawning.patrol_point_setup':
            assert v['pointName'] not in points
            points[v['pointName']] = position(r, area)
            continue
        if script not in ('systems.spawning.spawner_area', 'systems.spawning.spawner_patrol',
                          'npc.celebrity.celebrity_spawner'):
            continue
        assert r['container'] == r['cell_index'] == '0' and float(r['qx']) == float(r['qz']) == 0
        x, z, y = position(r, area)
        c = dict(id=int(r['objid']), row=line, x=x, z=z, y=y,
                 heading=math.degrees(2 * math.atan2(float(r['qy']), float(r['qw']))))
        if script == 'npc.celebrity.celebrity_spawner':
            assert not v.get('npc_name')
            c.update(item=v['spawns'], z=z + .5)
            npcs.append(c)
            continue
        type_name = v['strSpawns']
        if type_name not in types:
            path = dt / f'spawning/ground_spawning/types/{type_name}.tab'
            entries = (table(path) if path.is_file() else
                       [{'strItem': type_name, 'fltSize': 8}])  # DSRC fallback for direct creature IDs
            types[type_name] = [dict(item=e['strItem'], clearance=float(e['fltSize'] or 1),
                                     mobile='dead_forest_' + e['strItem']) for e in entries]
            assert types[type_name] and all(e['item'] in creatures for e in types[type_name])
        c.update(type=type_name, count=int(v['intSpawnCount']), radius=float(v['fltRadius']),
                 respawnMin=float(v.get('fltRespawnTime', v['fltMinSpawnTime'])),
                 respawnMax=float(v.get('fltRespawnTime', v['fltMaxSpawnTime'])),
                 behavior=int(v['intDefaultBehavior']), goodLocation=int(v['intGoodLocationSpawner']))
        assert c['count'] > 0 and c['goodLocation'] == 0 and 0 <= c['respawnMin'] <= c['respawnMax']
        if script.endswith('spawner_patrol'):
            c.update(pathType=v['patrolPathType'], pointNames=v['strPatrolPointNames'].strip(':').split(':'))
            patrols.append(c)
        else:
            assert c['behavior'] in (1, 2)
            controllers.append(c)
    for c in patrols:
        names = c.pop('pointNames')
        c['points'] = [[c['x'], c['z'], c['y']]] + [points[n] for n in names if n in points]
        c['missingPoints'] = [n for n in names if n not in points]
        assert c['count'] < len(c['points'])
    for line, r in enumerate(table(dt / 'spawning/dungeon/ep3_forest_webweaver.tab'), 3):
        assert not any(r.get(k) for k in ('name', 'spawn_objvar', 'special_room'))
        cave.append(dict(row=line, item=r['spawns'], room=r['room'], x=float(r['loc_x']),
                         z=float(r['loc_y']), y=float(r['loc_z']), heading=float(r['yaw']),
                         respawn=int(r['respawn_time'] or 0)))
    assert (len(controllers), len(patrols), len(npcs), len(cave)) == (87, 4, 11, 53)
    actors = {n['item'] for n in npcs}
    identities = (actors | {e['item'] for t in types.values() for e in t} | {r['item'] for r in cave}
                  | {'ep3_forest_kerritamba_assassin', 'ep3_forest_kerritamba_leader'})
    data = ['-- Generated by utils/kashyyyk/build_dead_forest_population.py.',
            '-- Coordinates use the standalone Dead Forest area origin. Type rows retain DSRC order and repeats.',
            'KashyyykDeadForestData = {', '\ttypes = {']
    for key, entries in sorted(types.items()):
        data.append('\t\t[' + lua(key) + '] = ' + lua(entries) + ',')
    data.append('\t},')
    for key, entries in [('controllers', controllers), ('patrols', patrols), ('npcs', npcs), ('cave', cave)]:
        data.append('\t' + key + ' = {')
        data.extend('\t\t' + lua(e) + ',' for e in entries)
        data.append('\t},')
    data.append('}')

    # Use the active includes, not similarly named unused copies.
    mobile_root = SCRIPTS / 'mobile'
    registered, visited = {}, set()

    def read_mobiles(path):
        path = path.resolve()
        if path in visited or not path.is_file():
            return
        visited.add(path)
        src = path.read_text(errors='replace')
        for child in re.findall(r'^\s*includeFile\("([^"]+)"\)', src, re.M):
            read_mobiles(mobile_root / child)
        template = re.search(r'CreatureTemplates:addCreatureTemplate\([^,]+,\s*"([^"]+)"', src)
        appearances = re.search(r'\btemplates\s*=\s*\{([^}]+)', src)
        if template and appearances:
            registered[template[1]] = re.findall(r'"object/mobile/([^"]+)"', appearances[1])

    read_mobiles(mobile_root / 'serverobjects.lua')
    dressed = {}
    for path in sorted((dt / 'npc_customization').glob('dressed_species_*.tab')):
        with path.open() as f:
            entries = list(csv.reader(f, delimiter='\t'))
        for i, key in enumerate(entries[0]):
            if key:
                dressed[key] = [r[i] for r in entries[2:] if len(r) > i and r[i]]
    balance = table(dt / 'mob/stat_balance.tab')
    mob_lines = ['-- Generated from DSRC creatures.tab and dressed species tables.',
                 '-- Dedicated identities keep other zones and old quest templates intact.',
                 'local profiles = {']
    for item in sorted(identities):
        r = creatures[item]
        template = r['template']
        apps = [template] if template.endswith('.iff') else dressed[template]
        if item == 'ep3_forest_wookiee_spirit_healer_01':
            # The supported client/server object uses the shorter EP3 filename.
            apps = ['ep3/wookiee_spirit_healer_01.iff']
        stem = Path(apps[0]).stem
        matches = [name for name, paths in registered.items() if apps[0] in paths]
        base = item if item in registered else stem if stem in matches else matches[0] if len(matches) == 1 else None
        if item == 'ep3_forest_exemplar_zheus':
            base = 'dressed_ep3_forest_outcast_assassin_01'
        if base is None:
            # Moufs have a shared object and no registered legacy creature profile.
            assert template == 'mouf.iff', (item, apps, matches)
            base = 'Creature'
        script = next((s.split('.', 1)[1] for s in r['scripts'].split(',') if s.startswith('conversation.')), '')
        script_name = None
        if script:
            source_script = (server / 'script/conversation' / (script + '.java')).read_text()
            assigned = set(re.findall(r'setName\(self, new string_id\("([^"]+)", "([^"]+)"\)\)', source_script))
            assert len(assigned) <= 1, item
            script_name = next(iter(assigned), None)
        if r['scripts'] == 'npc.converse.junk_dealer':
            script = 'ep3_forest_kerritamba_dealer'  # Existing Core3 equivalent.
        conv = script + '_convo' if script else ''
        if 'npc.faction_recruiter.recruiter_setup' in r['scripts'] and r['pvpFaction'].lower() == 'rebel':
            conv = 'rebelRecruiterConvoTemplate'
        elif conv:
            assert any(p.name == conv + '.lua' for p in (mobile_root / 'conversations').rglob(conv + '.lua')), conv
        # DSRC uses the object template's NPC name when there is no creature_names key.
        display = '@mob/creature_names:' + item
        if script_name:
            display = '@' + ':'.join(script_name)
        elif item in actors:
            app = Path(apps[0])
            tpf = shared / 'object/mobile' / app.parent / ('shared_' + app.stem + '.tpf')
            match = re.search(r'objectName\s*=\s*"([^"]+)"\s+"([^"]+)"', tpf.read_text())
            assert match, item
            display = '@' + match[1] + ':' + match[2]
        faction = r['pvpFaction'].lower() if r['pvpFaction'].lower() in {'imperial', 'rebel'} else r['pvpFaction']
        flags = ('NONE' if item in actors or r['invulnerable'] == '1' else
                 'ATTACKABLE + AGGRESSIVE + ENEMY' if int(r['aggressive'] or 0) else 'ATTACKABLE')
        options = ['AIENABLED']
        if flags == 'NONE':
            options.append('INVULNERABLE')
        if conv:
            options.extend(['CONVERSABLE', 'INTERESTING'])
        if faction in {'rebel', 'imperial'} and flags != 'NONE':
            options.append('FACTIONAGGRO')
        fields = dict(objectName=display, customName='', conversationTemplate=conv,
                      socialGroup=r['socialGroup'], faction=faction, aggroRadius=int(r['aggressive'] or 0),
                      templates=['object/mobile/' + a for a in apps])
        if flags != 'NONE':
            level = int(r['BaseLevel'])
            prefix = {'NORMAL': '', 'ELITE': 'Elite_', 'BOSS': 'Boss_'}[r['difficultyClass']]
            def stat(modifier, column):
                return float(balance[max(1, level + int(r[modifier] or 0)) - 1][prefix + column])

            hp = stat('StatLevelModifier', 'HP')
            damage = stat('Damagelevelmodifier', 'damagePerSecond') * float(r['primary_weapon_speed'] or 2)
            fields.update(level=level, chanceHit=stat('ToHitLevelModifier', 'ToHit') / 100,
                          baseHAM=int(hp * .9), baseHAMmax=int(hp * 1.1), baseXp=int(balance[level - 1]['XP']),
                          damageMin=math.floor(damage * .5 + .5), damageMax=math.floor(damage * 1.5 + .5))
        if r['minScale'] or r['maxScale']:
            fields['scale'] = (float(r['minScale'] or 1) + float(r['maxScale'] or 1)) / 2
        loot = r['lootList']
        if loot and (SCRIPTS / 'loot/groups/kashyyyk' / (loot + '.lua')).is_file():
            fields['lootGroups'] = [dict(groups=[dict(group=loot, chance=10000000)], lootChance=10000000)]
        record = lua(fields)
        traits = []
        if flags != 'NONE':
            if r['stalker'] in {'1', 'yes'}:
                traits.append('STALKER')
            if r['death_blow'] in {'1', 'yes'}:
                traits.append('KILLER')
        mob_lines.append('\t{' + base + ', ' + lua('dead_forest_' + item) + ', ' +
                         record[:-1] + ', randomNameType = NAME_TAG, pvpBitmask = ' + flags +
                         ', creatureBitmask = ' + (' + '.join(traits) or 'NONE') +
                         ', optionsBitmask = ' + ' + '.join(options) + '}},')
    mob_lines += ['}', '', 'for _, profile in ipairs(profiles) do',
                  '\tCreatureTemplates:addCreatureTemplate(profile[1]:new(profile[3]), profile[2])', 'end']
    print(f"{len(controllers)} ambient controllers, {sum(c['count'] for c in controllers)} slots; "
          f"{len(patrols)} patrols, {sum(c['count'] for c in patrols)} slots; {len(types)} types; "
          f"{len(npcs)} named actors; {len(cave)} cave rows; {len(identities)} profiles.")
    print('Missing DSRC waypoint references:', sum(len(c['missingPoints']) for c in patrols))
    return {SCRIPTS / 'screenplays/kashyyyk/kashyyyk_dead_forest_data.lua': '\n'.join(data) + '\n',
            mobile_root / 'custom_content/kashyyyk_dead_forest_profiles.lua': '\n'.join(mob_lines) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('dsrc', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate(args.dsrc).items():
        if args.check:
            assert path.read_text(encoding='utf-8') == content, str(path)
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
